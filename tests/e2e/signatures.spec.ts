import { expect, test } from "@playwright/test";

const png = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j1ioAAAAASUVORK5CYII=";

test("creates an imported signature, sets defaults, and preserves its images and snapshot after restart", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Settings (⌘,)" }).click();
  const settings = page.getByRole("dialog", { name: "Settings", exact: true });
  await settings.getByRole("button", { name: "Signatures", exact: true }).click();
  await settings.getByRole("button", { name: "Add Signature" }).click();
  const editor = page.getByRole("dialog", { name: "New Signature" });
  await expect(editor.getByLabel("Name", { exact: true })).toBeFocused();
  await editor.getByLabel("Name", { exact: true }).fill("Work Full");
  await editor.getByRole("button", { name: "Import…", exact: true }).click();
  const importer = page.getByRole("dialog", { name: "Import Signature" });
  await importer.getByLabel("HTML", { exact: true }).fill(`<table cellpadding="0" cellspacing="8"><tr><td><img src="data:image/png;base64,${png}" alt="Logo" width="24"></td><td style="color:#245789">Alex Example<br>Designer</td><td></td></tr></table>`);
  await importer.getByRole("button", { name: "Import", exact: true }).click();
  await expect(editor.getByRole("textbox", { name: "Signature Content" }).locator("td")).toHaveCount(3);
  await editor.getByRole("button", { name: "Save", exact: true }).click();
  await settings.getByRole("button", { name: "Mail Accounts", exact: true }).click();
  await settings.getByRole("button", { name: "Signature Defaults…", exact: true }).first().click();
  const defaults = page.getByRole("dialog", { name: "Default Signatures" });
  await defaults.getByRole("combobox", { name: "New Messages", exact: true }).selectOption({ label: "Work Full" });
  await defaults.getByRole("button", { name: "Save", exact: true }).click();
  await settings.getByRole("button", { name: "Close", exact: true }).click();
  await page.setViewportSize({ width: 900, height: 600 });
  await page.getByRole("button", { name: "New Message (c)" }).click();
  const composer = page.getByRole("dialog", { name: "New Message", exact: true });
  const signature = composer.getByRole("textbox", { name: "Message Signature" });
  await expect(signature).toContainText("Alex Example");
  await expect(composer.getByRole("button", { name: /^Send ⌘/ })).toBeInViewport();
  await expect(signature.locator("img")).toHaveAttribute("src", `data:image/png;base64,${png}`);
  await composer.getByRole("textbox", { name: "Subject", exact: true }).fill("Signature snapshot");
  await composer.getByRole("textbox", { name: "Message Body" }).fill("Hello 😀");
  await composer.getByRole("button", { name: "Save and Close Draft" }).click();
  // Updating the library cannot rewrite the draft's snapshot.
  await page.getByRole("button", { name: "Settings (⌘,)" }).click();
  await settings.getByRole("button", { name: "Signatures", exact: true }).click();
  await settings.getByRole("button", { name: "Edit", exact: true }).click();
  const edit = page.getByRole("dialog", { name: "Edit Signature" });
  await edit.getByRole("textbox", { name: "Signature Content" }).fill("Updated library signature");
  await edit.getByRole("button", { name: "Save", exact: true }).click();
  await settings.getByRole("button", { name: "Close", exact: true }).click();
  await page.reload();
  await page.getByRole("button", { name: /Choose folder, current folder/ }).click();
  await page.getByRole("group", { name: "Folders" }).getByRole("button", { name: "Drafts", exact: true }).click();
  await page.getByText("Signature snapshot", { exact: true }).click();
  await expect(composer.getByRole("textbox", { name: "Message Body" })).toHaveText("Hello 😀");
  await expect(signature).toContainText("Alex Example");
  await expect(signature).not.toContainText("Updated library");
  await expect(signature.locator("img")).toHaveAttribute("width", "24");
  await expect(signature.locator("table")).toHaveAttribute("cellspacing", "8");
  await expect(composer.getByRole("textbox", { name: "Message Signature" })).toHaveCount(1);
  await composer.getByRole("combobox", { name: "Signature", exact: true }).selectOption("");
  await expect(signature).toHaveCount(0);
  await expect(composer.getByRole("textbox", { name: "Message Body" })).toHaveText("Hello 😀");
});

test("signature forms contain keyboard focus and suspend letter commands until dismissed", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Settings (⌘,)" }).click();
  const settings = page.getByRole("dialog", { name: "Settings", exact: true });
  await settings.getByRole("button", { name: "Signatures", exact: true }).click();
  const add = settings.getByRole("button", { name: "Add Signature" });
  await add.focus(); await page.keyboard.press("Enter");
  const editor = page.getByRole("dialog", { name: "New Signature" });
  await page.keyboard.type("c");
  await expect(editor.getByLabel("Name", { exact: true })).toHaveValue("c");
  await expect(page.getByRole("dialog", { name: "New Message", exact: true })).toHaveCount(0);
  const save = editor.getByRole("button", { name: "Save", exact: true });
  await save.focus(); await page.keyboard.press("Tab");
  await expect(editor.getByRole("button", { name: "Close", exact: true })).toBeFocused();
  const importButton = editor.getByRole("button", { name: "Import…", exact: true });
  await importButton.focus(); await page.keyboard.press("Space");
  await expect(page.getByRole("dialog", { name: "Import Signature" }).getByLabel("HTML", { exact: true })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(importButton).toBeFocused();
  await expect(editor).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(add).toBeFocused();
  await expect(settings.getByText("No signatures yet", { exact: true })).toBeVisible();
});
